"""Translation maintenance for Nxt: extract, compile, check, share terms.

    python scripts/i18n.py update [--locale zh-CN]
    python scripts/i18n.py build
    python scripts/i18n.py check [--locale zh-CN]
    python scripts/i18n.py terms --freecad PATH-TO-FREECAD-SOURCE

update extracts every string from the Python and QML code, and from the
inspector templates (TOML, which lupdate cannot read), into Nxt.ts and
the locale's file, carrying over translations of the same text. build
compiles each Nxt_<locale>.ts to its .qm. check reports how complete a
locale is, that placeholders survive, and that each .qm is exactly what
its .ts compiles to. terms lists the text FreeCAD translates itself.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
import types
import xml.etree.ElementTree as ET
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "freecad" / "nxt"
TRANSLATIONS_DIR = SRC_DIR / "resources" / "translations"
TEMPLATES_DIR = SRC_DIR / "resources" / "inspector"
TERMS_FILE = SRC_DIR / "app" / "freecad_terms.py"
TEMPLATE_CONTEXT = "NxtTemplate"
DEFAULT_LOCALE = "zh-CN"
PLACEHOLDER = re.compile(r"%[0-9]+|%[sd]|{[A-Za-z0-9_]*}")
#: Template keys whose values are shown to the user.
SHOWN_KEYS = ("title", "hint", "label")


def find_tool(name: str) -> Path | None:
    """A Qt tool, on PATH or beside this Python."""
    found = shutil.which(name)
    if found:
        return Path(found)
    for folder in (Path(sys.prefix) / "bin", Path(sys.prefix) / "Scripts"):
        for candidate in (folder / name, folder / (name + ".exe")):
            if candidate.is_file():
                return candidate
    return None


def source_files() -> list[str]:
    return sorted(str(p) for ext in ("*.py", "*.qml")
                  for p in SRC_DIR.rglob(ext))


def template_strings() -> Iterator[tuple[str, str]]:
    """(template id, text) for every shown string of every template."""
    for path in sorted(TEMPLATES_DIR.glob("*.toml")):
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        for template in data.get("template", ()):
            yield from ((template["id"], text)
                        for text in _shown(template))


def _shown(node: object) -> Iterator[str]:
    if isinstance(node, list):
        for item in node:
            yield from _shown(item)
    elif isinstance(node, dict):
        for key, value in node.items():
            if key in SHOWN_KEYS and isinstance(value, str) and value:
                yield value
            elif key == "labels" and isinstance(value, list):
                yield from (str(v) for v in value if v)
            elif key == "choices" and isinstance(value, dict):
                yield from (str(v) for v in value.values() if v)
            else:
                yield from _shown(value)


def _template_source(folder: Path) -> Path:
    """The templates' text as calls lupdate reads, in a scratch file."""
    lines = ["# Generated by scripts/i18n.py; never committed.",
             "from freecad.nxt.app.i18n import translate", ""]
    seen = set()
    for template_id, text in template_strings():
        if (template_id, text) not in seen:
            seen.add((template_id, text))
            lines.append("translate(%r, %r, %r)"
                         % (TEMPLATE_CONTEXT, text, template_id))
    path = folder / "inspector_templates.py"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _translations(path: Path) -> dict[str, str]:
    """Finished translations in a .ts file, by source text."""
    if not path.exists():
        return {}
    found: dict[str, str] = {}
    for message in ET.parse(path).getroot().iter("message"):
        translation = message.find("translation")
        if translation is None or translation.get("type") or \
                not (translation.text or "").strip():
            continue
        found.setdefault(message.findtext("source") or "",
                         translation.text or "")
    return found


def _carry_over(path: Path, known: dict[str, str]) -> int:
    """Fill untranslated messages whose text was translated before."""
    tree = ET.parse(path)
    filled = 0
    for message in tree.getroot().iter("message"):
        translation = message.find("translation")
        source = message.findtext("source") or ""
        if translation is not None and translation.get("type") == \
                "unfinished" and source in known:
            translation.text = known[source]
            del translation.attrib["type"]
            filled += 1
    if filled:
        tree.write(path, encoding="utf-8", xml_declaration=True)
    return filled


def cmd_update(args: argparse.Namespace) -> int:
    lupdate = find_tool("pyside6-lupdate")
    if lupdate is None:
        print("pyside6-lupdate not found", file=sys.stderr)
        return 1
    template = TRANSLATIONS_DIR / "Nxt.ts"
    locale = TRANSLATIONS_DIR / ("Nxt_%s.ts" % args.locale)
    known = _translations(locale)
    with tempfile.TemporaryDirectory() as folder:
        files = source_files() + [str(_template_source(Path(folder)))]
        result = subprocess.run(
            [str(lupdate), *files, "-no-obsolete", "-locations", "none",
             "-ts", str(template), str(locale)])
    if result.returncode:
        return result.returncode
    print("carried over %d translation(s)" % _carry_over(locale, known))
    return 0


def compile_ts(ts: Path, qm: Path) -> int:
    lrelease = find_tool("pyside6-lrelease")
    if lrelease is None:
        print("pyside6-lrelease not found", file=sys.stderr)
        return 1
    return subprocess.run([str(lrelease), "-silent", str(ts), "-qm",
                           str(qm)]).returncode


def locale_files() -> list[Path]:
    return sorted(TRANSLATIONS_DIR.glob("Nxt_*.ts"))


def cmd_build(_args: argparse.Namespace) -> int:
    status = 0
    for ts in locale_files():
        print("compiling", ts.name)
        status |= compile_ts(ts, ts.with_suffix(".qm"))
    return status


def placeholder_problems(ts: Path) -> list[str]:
    """Translations whose %1, %s or {name} differ from their source."""
    problems = []
    for message in ET.parse(ts).getroot().iter("message"):
        translation = message.find("translation")
        text = translation.text if translation is not None else ""
        if not text or (translation is not None
                        and translation.get("type")):
            continue
        source = message.findtext("source") or ""
        if sorted(PLACEHOLDER.findall(source)) != \
                sorted(PLACEHOLDER.findall(text)):
            problems.append("%s: %r -> %r" % (ts.name, source, text))
    return problems


def stale_qm(ts: Path) -> bool:
    """The committed .qm is not what its .ts compiles to."""
    qm = ts.with_suffix(".qm")
    with tempfile.TemporaryDirectory() as folder:
        built = Path(folder) / qm.name
        if compile_ts(ts, built):
            return True
        return not qm.exists() or qm.read_bytes() != built.read_bytes()


def cmd_check(args: argparse.Namespace) -> int:
    ts = TRANSLATIONS_DIR / ("Nxt_%s.ts" % args.locale)
    if not ts.exists():
        print("%s does not exist" % ts.name, file=sys.stderr)
        return 1
    messages = list(ET.parse(ts).getroot().iter("message"))
    done = sum(1 for m in messages
               if (m.find("translation") is not None
                   and not m.find("translation").get("type")  # type: ignore
                   and (m.findtext("translation") or "").strip()))
    print("%s: %d of %d translated" % (ts.name, done, len(messages)))
    problems = placeholder_problems(ts)
    for problem in problems:
        print("placeholder:", problem)
    if stale_qm(ts):
        print("%s does not match its .ts: run build"
              % ts.with_suffix(".qm").name)
        return 1
    return 1 if problems else 0


def nxt_texts() -> set[str]:
    """Every text Nxt shows: from Nxt.ts and the templates."""
    texts = {m.findtext("source") or "" for m in
             ET.parse(TRANSLATIONS_DIR / "Nxt.ts").getroot().iter("message")}
    return texts | {text for _id, text in template_strings()}


def cmd_terms(args: argparse.Namespace) -> int:
    """List Nxt's text FreeCAD translates, with FreeCAD's context."""
    sys.path.insert(0, str(ROOT))
    sys.modules.setdefault("FreeCAD", types.ModuleType("FreeCAD"))
    from freecad.nxt.app.i18n import PREFIX, term_key

    wanted = set()
    for text in nxt_texts():
        wanted.add(term_key(text))
        if text.startswith(PREFIX):
            wanted.add(term_key(text[len(PREFIX):]))
    #: key -> {(context, source): how many languages translate it}
    seen: dict[str, dict[tuple[str, str], int]] = {}
    for ts in Path(args.freecad).rglob("*_*.ts"):
        for context in ET.parse(ts).getroot().iter("context"):
            name = context.findtext("name") or ""
            for message in context.iter("message"):
                source = message.findtext("source") or ""
                key = term_key(source)
                translation = message.find("translation")
                if key in wanted and translation is not None and \
                        not translation.get("type") and translation.text:
                    found = seen.setdefault(key, {})
                    found[(name, source)] = found.get((name, source), 0) + 1
    lines = ['"""Generated by scripts/i18n.py terms: Nxt\'s text FreeCAD '
             'translates too.', "",
             "term_key(text) -> (FreeCAD's context, FreeCAD's source text).",
             '"""', "", "TERMS: dict[str, tuple[str, str]] = {"]
    for key in sorted(seen):
        context, source = max(seen[key].items(),
                              key=lambda kv: (kv[1], kv[0]))[0]
        line = "    %r: (%r, %r)," % (key, context, source)
        lines.append(line if len(line) < 80 else
                     "    %r:\n        (%r, %r)," % (key, context, source))
    lines.append("}")
    TERMS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("%d terms written to %s" % (len(seen), TERMS_FILE.name))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("update", "check"):
        commands.add_parser(name).add_argument(
            "--locale", default=DEFAULT_LOCALE)
    commands.add_parser("build")
    commands.add_parser("terms").add_argument("--freecad", required=True)
    args = parser.parse_args()
    return {"update": cmd_update, "build": cmd_build, "check": cmd_check,
            "terms": cmd_terms}[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
